import { toolFixture } from './tool-test-fixture.mjs'
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const script = resolve(import.meta.dirname, 'build-cached.mjs')
test('fresh archives reuse verified output and rebuild changed or damaged inputs', (t) => {
  const { root: scratch, env: fixtureEnv } = toolFixture(t)
  const cache = join(scratch, 'cache')
  const source = join(scratch, 'source')
  const app = join(source, 'apps', 'desktop')
  mkdirSync(app, { recursive: true })
  writeFileSync(join(source, 'bun.lock'), 'lock v1')
  writeFileSync(join(app, 'source.txt'), 'first')
  writeFileSync(join(app, 'build.mjs'), `import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'; mkdirSync('out', { recursive: true }); writeFileSync('out/result', readFileSync('source.txt')); console.log('BUILT'); if (process.env.FAIL_BUILD) process.exit(1)`)
  const run = (cwd, env = {}) => spawnSync(process.execPath, [script, 'out', process.execPath, 'build.mjs'], { cwd, encoding: 'utf8', env: { ...fixtureEnv, JUNO_BUILD_CACHE_DIR: cache, ...env } })
  const first = run(app)
  assert.equal(first.status, 0, first.stderr)
  assert.match(first.stdout, /BUILT/)
  assert.doesNotMatch(run(app).stdout, /BUILT/)
  mkdirSync(join(app, 'e2e'))
  writeFileSync(join(app, 'e2e', 'example.spec.ts'), 'test only')
  assert.doesNotMatch(run(app).stdout, /BUILT/)
  for (const file of ['packages/engine/test/boot.test.ts', 'apps/desktop/test/session.test.ts', 'scripts/cache.test.mjs']) {
    const target = join(source, file)
    mkdirSync(resolve(target, '..'), { recursive: true })
    writeFileSync(target, 'test only')
    assert.doesNotMatch(run(app).stdout, /BUILT/)
    writeFileSync(target, 'changed test')
    assert.doesNotMatch(run(app).stdout, /BUILT/)
  }
  // Seeds and migrations affect snapshots even though the fake is a test dependency.
  for (const file of ['packages/fake-slack/src/seed.ts', 'packages/store/src/migrations.ts', 'packages/sync/src/boot.ts']) {
    const target = join(source, file)
    mkdirSync(resolve(target, '..'), { recursive: true })
    writeFileSync(target, 'source input')
    assert.match(run(app).stdout, /BUILT/)
  }
  const fresh = join(scratch, 'fresh')
  cpSync(source, fresh, { recursive: true })
  const freshApp = join(fresh, 'apps', 'desktop')
  rmSync(join(freshApp, 'out'), { recursive: true })
  const restored = run(freshApp)
  assert.equal(restored.status, 0, restored.stderr)
  assert.match(restored.stdout, /restored/)
  assert.equal(readFileSync(join(freshApp, 'out/result'), 'utf8'), 'first')
  writeFileSync(join(freshApp, 'out/result'), 'wrong')
  assert.match(run(freshApp).stdout, /restored/)
  assert.equal(readFileSync(join(freshApp, 'out/result'), 'utf8'), 'first')
  for (const entry of readdirSync(join(cache, 'apps-desktop')).filter((name) => !name.startsWith('.'))) writeFileSync(join(cache, 'apps-desktop', entry, 'result'), 'bad cache')
  rmSync(join(freshApp, 'out'), { recursive: true })
  assert.match(run(freshApp).stdout, /BUILT/)
  assert.equal(readFileSync(join(freshApp, 'out/result'), 'utf8'), 'first')
  writeFileSync(join(freshApp, 'extra-input'), 'new file')
  assert.match(run(freshApp).stdout, /BUILT/)
  rmSync(join(freshApp, 'extra-input'))
  assert.match(run(freshApp).stdout, /restored/)
  writeFileSync(join(freshApp, 'source.txt'), 'second')
  assert.match(run(freshApp).stdout, /BUILT/)
  assert.equal(readFileSync(join(freshApp, 'out/result'), 'utf8'), 'second')
  writeFileSync(join(fresh, 'bun.lock'), 'lock v2')
  assert.match(run(freshApp).stdout, /BUILT/)
  assert.match(run(freshApp, { JUNO_UNMINIFIED: '1' }).stdout, /BUILT/)
  assert.match(run(freshApp, { JUNO_REBUILD: '1' }).stdout, /BUILT/)
  writeFileSync(join(freshApp, 'source.txt'), 'failed')
  assert.equal(run(freshApp, { FAIL_BUILD: '1' }).status, 1)
  assert.match(run(freshApp).stdout, /BUILT/)

  // The same checks work in a real checkout, including untracked and deleted inputs.
  assert.equal(spawnSync('git', ['init', '-q'], { cwd: fresh, env: fixtureEnv }).status, 0)
  writeFileSync(join(fresh, '.gitignore'), 'out/\n.env*\n')
  assert.match(run(freshApp).stdout, /BUILT/)
  assert.doesNotMatch(run(freshApp).stdout, /BUILT/)
  writeFileSync(join(freshApp, '.env.production'), 'VITE_EXAMPLE=one')
  assert.match(run(freshApp).stdout, /BUILT/)
  writeFileSync(join(freshApp, '.env.production'), 'VITE_EXAMPLE=two')
  assert.match(run(freshApp).stdout, /BUILT/)
  writeFileSync(join(freshApp, 'untracked.txt'), 'new')
  assert.match(run(freshApp).stdout, /BUILT/)
  assert.equal(spawnSync('git', ['add', '.'], { cwd: fresh, env: fixtureEnv }).status, 0)
  // A deleted file still in the index is not an input: the tree matches the earlier build again.
  rmSync(join(freshApp, 'untracked.txt'))
  assert.match(run(freshApp).stdout, /restored/)
})
