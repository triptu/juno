import { expect, test } from '@playwright/test'

// One editing flow covers wrapping, invalid drafts, both save keys and cancellation.
test('edit a long note, save a new line, cancel a draft and save with Command', async ({ page }) => {
  await page.goto('/#/MemoryDocsPage?__state=behaviour/edit-keys')
  const note = page.locator('[data-memory-doc="people"] [data-memory-entry]').first()
  const field = page.getByRole('textbox', { name: 'Note' })
  const log = page.locator('[data-activation-log]')
  const edit = async () => {
    await note.hover()
    await note.getByRole('button', { name: /^Edit / }).click()
    await expect(field).toBeFocused()
  }
  const original = await note.locator('[dir="auto"]').first().innerText()
  await edit()
  await expect(field).toHaveValue(original)
  const box = await field.evaluate(element => ({ scrollWidth: element.scrollWidth, clientWidth: element.clientWidth, scrollHeight: element.scrollHeight, clientHeight: element.clientHeight }))
  expect(box.scrollWidth).toBeLessThanOrEqual(box.clientWidth)
  expect(box.scrollHeight).toBeLessThanOrEqual(box.clientHeight)
  await field.fill('')
  await field.press('Enter')
  await expect(field).toBeVisible()
  await expect(log).not.toHaveText('save')
  await field.fill(original)
  await field.press('End')
  await field.press('Shift+Enter')
  await field.pressSequentially('Out on Fridays.')
  await field.press('Enter')
  await expect(log).toHaveText('save')
  await expect(field).toHaveCount(0)
  await expect.poll(() => note.locator('[dir="auto"]').first().innerText()).toMatch(/\nOut on Fridays\.$/)
  const saved = await note.locator('[dir="auto"]').first().innerText()
  await edit()
  await field.fill('Unfinished draft')
  await field.press('Escape')
  await expect(field).toHaveCount(0)
  await expect(note.locator('[dir="auto"]').first()).toHaveText(saved)
  await expect(log).toHaveText('save cancel')
  await edit()
  await field.press('Meta+Enter')
  await expect(log).toHaveText('save cancel save')
  await expect(field).toHaveCount(0)
})
